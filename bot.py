async def _delete_post(context: ContextTypes.DEFAULT_TYPE):
    data = context.job.data
    try:
        await context.bot.delete_message(chat_id=data["chat_id"], message_id=data["message_id"])
    except Exception:
        pass


def _schedule_deletion(context: ContextTypes.DEFAULT_TYPE, message_id: int):
    """Schedule auto-deletion of a channel post after POST_LIFETIME_HOURS.

    Wrapped in its own try/except so that job-scheduling failures don't
    cause the post-publish flow to report an error to the user.
    """
    if POST_LIFETIME_HOURS <= 0:
        return
    try:
        if context.job_queue is None:
            logger.warning("JobQueue not available — skipping auto-deletion scheduling")
            return
        context.job_queue.run_once(
            _delete_post,
            when=POST_LIFETIME_HOURS * 3600,
            data={"chat_id": f"@{TARGET_CHANNEL}", "message_id": message_id},
            name=f"delete_post_{message_id}",
        )
    except Exception:
        logger.exception("Failed to schedule post deletion – post remains live")


async def _cleanup_chat_messages(context: ContextTypes.DEFAULT_TYPE, user_id: int, message_ids: list[int]):
    """Delete all bot messages in the private chat up to the start message."""
    for msg_id in message_ids:
        try:
            await context.bot.delete_message(chat_id=user_id, message_id=msg_id)
        except Exception:
            logger.debug("Could not delete message %s in chat %s", msg_id, user_id)


def _check_datetime_in_text(text: str) -> bool:
    """Check if the OCR text contains a date/time matching the current time.

    Accepts a screenshot only if it shows today's date (in any common
    format) or a time within ±10 minutes of now.
    """
    now = datetime.now()
    text_compact = re.sub(r"\s+", "", text)
    text_lower = text.lower()

    date_formats = [
        now.strftime("%d%m%Y"),
        now.strftime("%y%m%Y"),
        now.strftime("%Y%m%d"),
        now.strftime("%d%m%y"),
        now.strftime("%d.%m.%Y"),
        now.strftime("%d.%m.%y"),
        now.strftime("%d/%m/%Y"),
        now.strftime("%d-%m-%Y"),
        now.strftime("%Y-%m-%d"),
    ]

    for ds in date_formats:
        if ds in text_compact or ds.lower() in text_lower:
            return True

    for delta in range(-10, 11):
        check_time = now + timedelta(minutes=delta)
        time_str = check_time.strftime("%H:%M")
        time_compact = check_time.strftime("%H%M")
        if time_str in text or time_compact in text_compact:
            return True

    return False


async def verify_payment_screenshot(image_path: str) -> tuple[bool, str | None, str]:
    """Automatically verify a payment screenshot using OCR.

    Returns a tuple of ``(verification_passed, check_number_or_None, ocr_text)``
    where *check_number* is the payment reference extracted from the OCR
    text and *ocr_text* is the raw normalized OCR text used for duplicate
    detection.
    """
    if _ocr_reader is None:
        return False, None, ""

    try:
        results = _ocr_reader.readtext(image_path, detail=0)
        text = " ".join(results).lower()
    except Exception:
        return False, None, ""

    logger.info("OCR recognized text: %s", text)

    card_str = CARD_NUMBER.replace(" ", "").replace("-", "")
    text_compact = text.replace(" ", "").replace("-", "").replace("*", "")
    card_in_text = card_str in text_compact

    card_prefix = card_str[:4]
    card_suffix = card_str[-4:]
    card_prefix_found = card_prefix in text_compact
    card_suffix_found = card_suffix in text_compact

    # Require BOTH prefix and suffix — a different card won't match both
    card_any = card_in_text or (card_prefix_found and card_suffix_found)

    masked_card = re.search(
        rf"{card_prefix}[\dx*абвгдеёжзийклмнопрстуфхцчшщъыьэюяa-z\*\•]{{6,}}{card_suffix}",
        text_compact,
    ) is not None

    amount_patterns = [
        rf"{PAYMENT_AMOUNT}\.0+\s*byn",
        rf"{PAYMENT_AMOUNT},0+\s*byn",
        rf"{PAYMENT_AMOUNT}\s*byn",
        rf"{PAYMENT_AMOUNT}\.0+\s*brl",
        rf"{PAYMENT_AMOUNT}\s*brl",
        rf"{PAYMENT_AMOUNT}\.0+\s*бел?о?р?у?с?с?к?и?х?\s*руб",
        rf"{PAYMENT_AMOUNT}\.0+\s*руб",
        rf"{PAYMENT_AMOUNT}\s*бел?о?р?у?с?с?к?и?х?\s*руб",
        rf"{PAYMENT_AMOUNT}\s*руб",
    ]

    amount_found = any(
        re.search(pattern, text, re.IGNORECASE | re.DOTALL) for pattern in amount_patterns
    )

    if not amount_found:
        amount_found = bool(
            re.search(rf"{PAYMENT_AMOUNT}\.\d{{1,2}}\s*(byn|brl|руб|бел)", text, re.IGNORECASE)
            or re.search(rf"{PAYMENT_AMOUNT},\d{{1,2}}\s*(byn|brl|руб|бел)", text, re.IGNORECASE)
        )

    payment_keywords = [
        "успешно",
        "проведена",
        "завершена",
        "карта получателя",
        "сумма перевода",
        "номер чека",
        "банк",
    ]
    keywords_found = any(kw in text for kw in payment_keywords)

    datetime_found = _check_datetime_in_text(text)

    logger.info(
        "Verification: amount_found=%s, card_any=%s, keywords=%s, masked_card=%s, datetime_found=%s",
        amount_found, card_any, keywords_found, masked_card, datetime_found,
    )

    verified = (
        amount_found and card_any
        and (keywords_found or masked_card)
        and datetime_found
    )

    check_number = _extract_check_number(text) if verified else None
    return verified, check_number, text


async def error_handler(update: object, context: ContextTypes.DEFAULT_TYPE):
    logger.error("Exception while handling update:", exc_info=context.error)


def main():
    if not BOT_TOKEN:
        logger.error("BOT_TOKEN environment variable is not set!")
        raise SystemExit(1)

    request = HTTPXRequest(
        read_timeout=60,
        connect_timeout=30,
        write_timeout=60,
    )
    application = Application.builder().token(BOT_TOKEN).request(request).build()

    db_ok = _init_db()

    application.add_handler(CommandHandler("start", start))
    application.add_handler(CallbackQueryHandler(button_handler))
    application.add_handler(
        MessageHandler(filters.PHOTO & filters.ChatType.PRIVATE, handle_photo)
    )
    application.add_handler(
        MessageHandler(
            filters.TEXT & ~filters.COMMAND & filters.ChatType.PRIVATE, handle_text
        )
    )
    application.add_error_handler(error_handler)

    logger.info("Bot started. Target channel: @%s", TARGET_CHANNEL)
    logger.info("Card: %s, Amount: %s BYN", CARD_NUMBER, PAYMENT_AMOUNT)
    logger.info("Duplicate detection: file_hash + pHash + file_unique_id + text_hash + check_number")
    logger.info("Supabase: %s", SUPABASE_URL or "NOT CONFIGURED")

    application.run_polling()


if __name__ == "__main__":
    main()

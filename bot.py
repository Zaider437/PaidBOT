def _extract_check_number(text: str) -> str | None:
    """Extract the payment check/reference number from OCR text.

    Looks for common labels that precede a check number and returns
    the token that follows. Returns *None* when nothing is found.
    The *text* argument should already be lowercased.
    """
    patterns = [
        r"номер\s*чека[:\s№]*([a-z0-9\-]{4,})",
        r"чек[:\s№]*([a-z0-9\-]{4,})",
        r"номер\s*оплаты[:\s]*([a-z0-9\-]{4,})",
        r"номер\s*транзакции[:\s]*([a-z0-9\-]{4,})",
        r"номер\s*платежа[:\s]*([a-z0-9\-]{4,})",
        r"номер\s*операции[:\s]*([a-z0-9\-]{4,})",
        r"идентификатор\s*плат[её]жа[:\s]*([a-z0-9\-]{4,})",
        r"идентификатор\s*транзакции[:\s]*([a-z0-9\-]{4,})",
        r"реквизиты[:\s]*([a-z0-9\-]{6,})",
        r"реф[:\s]*([a-z0-9\-]{4,})",
        r"референс[:\s]*([a-z0-9\-]{4,})",
        r"ref[:\s]*([a-z0-9]{4,})",
        r"transaction\s*id[:\s]*([a-z0-9\-]{4,})",
        r"оплата[:\s№]*([0-9]{4,})",
        r"номер[:\sу]*([0-9]{6,})",
    ]
    for pattern in patterns:
        match = re.search(pattern, text, re.IGNORECASE | re.DOTALL)
        if match:
            return match.group(1).strip()
    return None


def _store_screenshot(file_hash: str, image_hash: str, text_hash: str,
                      check_number: str | None, user_id: int, file_unique_id: str):
    """Persist a verified screenshot so it can't be reused."""
    supabase = _get_supabase()
    if supabase is None:
        return
    try:
        supabase.table("screenshots").insert({
            "file_hash": file_hash,
            "image_hash": image_hash,
            "text_hash": text_hash,
            "check_number": check_number,
            "file_unique_id": file_unique_id,
            "user_id": user_id,
            "created_at": datetime.now().isoformat(),
        }).execute()
    except Exception as e:
        # Ignore unique-constraint violations — they mean a race condition
        # caused the same file to be stored twice (the pre-checks should
        # prevent this, but concurrent requests can slip through).
        err_str = str(e)
        if "23505" in err_str or "duplicate" in err_str.lower():
            logger.debug("Ignoring duplicate insert (race condition)")
        else:
            logger.exception("Supabase _store_screenshot insert failed")



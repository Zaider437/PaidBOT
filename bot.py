async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    user_id = update.effective_user.id
    reset_user_state(user_id)
    state = get_user_state(user_id)
    state.state = State.START

    welcome = await update.message.reply_text(WELCOME_TEXT, reply_markup=START_BUTTONS)
    state.bot_message_ids.append(welcome.message_id)


async def button_handler(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()

    user_id = update.effective_user.id
    state = get_user_state(user_id)

    if query.data == "continue":
        state.state = State.AWAITING_PROOF
        await query.edit_message_text(
            PAYMENT_TEXT, reply_markup=PAYMENT_BUTTONS, parse_mode="HTML"
        )

    elif query.data == "paid":
        state.state = State.AWAITING_PROOF
        await query.edit_message_text(
            PROOF_REQUEST_TEXT, reply_markup=PROOF_SENT_BUTTONS
        )

    elif query.data == "resend_proof":
        state.state = State.AWAITING_PROOF
        await query.edit_message_text(
            PROOF_REQUEST_TEXT, reply_markup=PROOF_SENT_BUTTONS
        )


async def handle_photo(update: Update, context: ContextTypes.DEFAULT_TYPE):
    user_id = update.effective_user.id
    state = get_user_state(user_id)

    if state.state == State.AWAITING_POST:
        photo = update.message.photo[-1]
        caption = update.message.caption or ""

        try:
            sent = await context.bot.send_photo(
                chat_id=f"@{TARGET_CHANNEL}",
                photo=photo.file_id,
                caption=caption,
            )
            state.post_message_id = sent.message_id

            await _cleanup_chat_messages(context, user_id, state.bot_message_ids)

            final = await context.bot.send_message(chat_id=user_id, text=POST_RECEIVED_TEXT)
            state.bot_message_ids = [final.message_id]

            _schedule_deletion(context, sent.message_id)
            reset_user_state(user_id)
        except Exception:
            logger.exception("Failed to publish post")
            await update.message.reply_text(
                "Ошибка при публикации поста. Убедись, что бот "
                "добавлен в канал @{channel} с правом публиковать.".format(
                    channel=TARGET_CHANNEL
                )
            )
        return

    if state.state != State.AWAITING_PROOF:
        msg = await update.message.reply_text("Нажми кнопку «Продолжить» чтобы начать.")
        state.bot_message_ids.append(msg.message_id)
        return

    verif_msg = await update.message.reply_text(VERIFICATION_TEXT)
    state.bot_message_ids.append(verif_msg.message_id)

    photo = update.message.photo[-1]
    file = await context.bot.get_file(photo.file_id)

    with tempfile.NamedTemporaryFile(suffix=".jpg", delete=False) as tmp:
        await file.download_to_drive(custom_path=tmp.name)
        tmp_path = tmp.name

    file_hash = _compute_file_hash(tmp_path)
    image_hash = _compute_image_hash(tmp_path)

    # Check 1: file hash + perceptual hash (exact and visual duplicates)
    if _screenshot_exists(file_hash, image_hash):
        os.unlink(tmp_path)
        logger.info("Duplicate detected via file/image hash for user %s", user_id)
        fail_msg = await update.message.reply_text(
            DUPLICATE_SCREENSHOT_TEXT, reply_markup=PROOF_SENT_BUTTONS
        )
        state.bot_message_ids.append(fail_msg.message_id)
        return

    # Check 2: Telegram file_unique_id (same file content → same ID)
    if photo.file_unique_id and _file_unique_id_exists(photo.file_unique_id):
        os.unlink(tmp_path)
        logger.info("Duplicate detected via file_unique_id for user %s", user_id)
        fail_msg = await update.message.reply_text(
            DUPLICATE_SCREENSHOT_TEXT, reply_markup=PROOF_SENT_BUTTONS
        )
        state.bot_message_ids.append(fail_msg.message_id)
        return

    verified = False
    check_number = None
    ocr_text = ""
    try:
        verified, check_number, ocr_text = await verify_payment_screenshot(tmp_path)
    except Exception:
        logger.exception("OCR verification error")
        verified = False
    finally:
        os.unlink(tmp_path)

    if verified:
        # Check 3: normalized OCR text hash (catches re-encoded images
        # with different bytes but same content words)
        text_hash = _compute_text_hash(ocr_text)
        if _text_hash_exists(text_hash):
            logger.info("Duplicate detected via text_hash for user %s", user_id)
            fail_msg = await update.message.reply_text(
                DUPLICATE_SCREENSHOT_TEXT, reply_markup=PROOF_SENT_BUTTONS
            )
            state.bot_message_ids.append(fail_msg.message_id)
            return

        # Check 4: payment check/reference number
        if check_number and _check_number_exists(check_number):
            logger.info("Duplicate detected via check_number=%s for user %s",
                        check_number, user_id)
            fail_msg = await update.message.reply_text(
                DUPLICATE_CHECK_NUMBER_TEXT, reply_markup=PROOF_SENT_BUTTONS
            )
            state.bot_message_ids.append(fail_msg.message_id)
            return

        _store_screenshot(file_hash, image_hash, text_hash, check_number,
                          user_id, photo.file_unique_id)
        logger.info(
            "Payment verified for user %s — stored. "
            "check_number=%s, has_text_hash=%s",
            user_id, check_number, bool(text_hash),
        )
        state.payment_confirmed = True
        state.state = State.AWAITING_POST
        state.payment_verified_at = datetime.now()
        success_msg = await update.message.reply_text(VERIFICATION_SUCCESS)
        state.bot_message_ids.append(success_msg.message_id)
    else:
        fail_msg = await update.message.reply_text(VERIFICATION_FAIL, reply_markup=PROOF_SENT_BUTTONS)
        state.bot_message_ids.append(fail_msg.message_id)



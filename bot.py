def _init_db():
    """Initialize the Supabase client and verify the screenshots table.

    The ``screenshots`` table must be pre-created in the Supabase SQL
    editor.  See ``CREATE_TABLE_SQL`` above.
    """
    supabase = _get_supabase()
    if supabase is None:
        logger.warning(
            "SUPABASE_URL / SUPABASE_ANON_KEY not set — "
            "duplicate detection is DISABLED. Duplicate payments will PASS!"
        )
        return False

    try:
        supabase.table("screenshots").select("id").limit(0).execute()
        logger.info("Supabase table 'screenshots' verified — duplicate detection active")
        return True
    except Exception as e:
        logger.error(
            "Supabase table 'screenshots' not found or inaccessible. "
            "Duplicate detection DISABLED.\n"
            "RUN THIS SQL in Supabase SQL Editor:\n%s", e, CREATE_TABLE_SQL
        )
        return False


def _compute_file_hash(file_path: str) -> str:
    """Return the SHA-256 hex digest of the file at *file_path*."""
    h = hashlib.sha256()
    with open(file_path, "rb") as f:
        for chunk in iter(lambda: f.read(8192), b""):
            h.update(chunk)
    return h.hexdigest()


def _compute_image_hash(file_path: str) -> str:
    """Compute a perceptual hash (pHash via DCT) of the image.

    Falls back to a plain file hash when OpenCV cannot read the image.
    """
    img = cv2.imread(file_path, cv2.IMREAD_GRAYSCALE)
    if img is None:
        return _compute_file_hash(file_path)

    img_resized = cv2.resize(img, (32, 32))
    dct = cv2.dct(np.float32(img_resized))
    dct_low = dct[:8, :8]
    avg = dct_low.mean()
    diff = dct_low > avg
    return "".join(str(int(b)) for b in diff.flatten())


def _screenshot_exists(file_hash: str, image_hash: str) -> bool:
    """Return True if a screenshot with either hash is already stored."""
    supabase = _get_supabase()
    if supabase is None:
        return False
    try:
        resp = supabase.table("screenshots").select("id").or_(
            f"file_hash.eq.{file_hash},image_hash.eq.{image_hash}"
        ).limit(1).execute()
        return len(resp.data) > 0
    except Exception:
        logger.exception("Supabase _screenshot_exists query failed")
        return False


def _file_unique_id_exists(file_unique_id: str) -> bool:
    """Return True if this Telegram file_unique_id was already used.

    Telegram guarantees a stable ``file_unique_id`` for identical file
    content even across different users.
    """
    supabase = _get_supabase()
    if supabase is None:
        return False
    try:
        resp = (
            supabase.table("screenshots")
            .select("id")
            .eq("file_unique_id", file_unique_id)
            .limit(1)
            .execute()
        )
        return len(resp.data) > 0
    except Exception:
        logger.exception("Supabase _file_unique_id_exists query failed")
        return False


def _normalize_text(text: str) -> str:
    """Normalize OCR text for deduplication.

    Lowercases, removes whitespace, strips non-alphanumeric characters,
    and removes date/time patterns so that screenshots of the same
    payment taken at different times still produce the same hash.
    """
    text = text.lower()
    # Remove time patterns with colon: HH:MM, HH:MM:SS
    text = re.sub(r"\d{1,2}:\d{2}(:\d{2})?", "", text)
    # Remove dates with separator chars: DD.MM.YYYY, DD/MM/YYYY, YYYY-MM-DD
    text = re.sub(r"\d{1,2}[\./\-]\d{1,2}[\./\-]\d{2,4}", "", text)
    text = re.sub(r"\d{2,4}[\./\-]\d{2}[\./\-]\d{2,4}", "", text)
    text = re.sub(r"\s+", "", text)
    text = re.sub(r"[^a-z0-9]", "", text)
    return text


def _compute_text_hash(text: str) -> str:
    """Return a SHA-256 hash of the normalized OCR text."""
    normalized = _normalize_text(text)
    return hashlib.sha256(normalized.encode()).hexdigest()


